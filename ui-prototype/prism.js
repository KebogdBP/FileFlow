const root = document.documentElement;
const themeToggle = document.querySelector('#theme-toggle');
const languageButtons = document.querySelectorAll('[data-lang]');
const dropCard = document.querySelector('#drop-card');
const fileInput = document.querySelector('#file-input');
const currentName = document.querySelector('#current-name');
const qualityRange = document.querySelector('#quality-range');
const qualityValue = document.querySelector('#quality-value');
const toast = document.querySelector('#toast');
const rail = document.querySelector('#rail');
let language = localStorage.getItem('fileflow-language') || 'en';

function setTheme(theme) {
  root.dataset.theme = theme;
  themeToggle.checked = theme === 'dark';
  document.querySelector('meta[name="theme-color"]').content = theme === 'dark' ? '#101421' : '#f7f8ff';
  localStorage.setItem('fileflow-theme', theme);
}
setTheme(localStorage.getItem('fileflow-theme') || 'light');
themeToggle.addEventListener('change', () => setTheme(themeToggle.checked ? 'dark' : 'light'));

function setLanguage(nextLanguage) {
  language = nextLanguage;
  root.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const value = translations[language][node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((node) => {
    const value = translations[language][node.dataset.i18nHtml];
    if (value) node.innerHTML = value;
  });
  languageButtons.forEach((button) => button.classList.toggle('active', button.dataset.lang === language));
  localStorage.setItem('fileflow-language', language);
}
languageButtons.forEach((button) => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
setLanguage(language);

['dragenter','dragover'].forEach((eventName) => dropCard.addEventListener(eventName, (event) => { event.preventDefault(); dropCard.classList.add('drag'); }));
['dragleave','drop'].forEach((eventName) => dropCard.addEventListener(eventName, (event) => { event.preventDefault(); dropCard.classList.remove('drag'); }));
dropCard.addEventListener('drop', (event) => selectFiles(event.dataTransfer.files));
fileInput.addEventListener('change', () => selectFiles(fileInput.files));

function selectFiles(files) {
  if (!files?.length) return;
  currentName.textContent = files.length > 1 ? `${files.length} ${language === 'ru' ? 'файлов' : 'files'}` : files[0].name;
  document.querySelector('#workspace').scrollIntoView({behavior:'smooth',block:'start'});
}

qualityRange.addEventListener('input', () => { qualityValue.textContent = `${qualityRange.value}%`; });
document.querySelector('#run-button').addEventListener('click', (event) => {
  const button = event.currentTarget;
  button.classList.add('loading');
  button.querySelector('span').textContent = language === 'ru' ? 'Обработка…' : 'Processing…';
  setTimeout(() => {
    button.classList.remove('loading');
    button.querySelector('span').textContent = translations[language].run_local;
    toast.classList.add('show');
    setTimeout(() => toast.classList.remove('show'), 3200);
  }, 1050);
});

document.querySelectorAll('[data-intent]').forEach((button) => button.addEventListener('click', () => {
  const intent = button.dataset.intent;
  const labelMap = {
    audio: ['MP4','MP3'], video:['MOV','MP4'], telegram:['MP4','Telegram'], phone:['File','Mobile'], compress:['JPG','WebP'], web:['PNG','WebP'], document:['DOCX','PDF'], metadata:['JPG','Clean']
  };
  const formats = labelMap[intent] || ['JPG','WebP'];
  document.querySelector('.compare-stats>div:first-child b').textContent = formats[0];
  document.querySelector('.compare-stats>div:nth-of-type(2) b').textContent = formats[1];
  document.querySelector('#workspace').scrollIntoView({behavior:'smooth',block:'start'});
}));

const waveBars = document.querySelector('#wave-bars');
for (let index = 0; index < 62; index += 1) {
  const bar = document.createElement('i');
  const height = 10 + Math.abs(Math.sin(index * .72) * 39) + (index % 4) * 2;
  bar.style.height = `${height}px`;
  waveBars.appendChild(bar);
}

document.querySelector('#mobile-menu').addEventListener('click', () => rail.classList.add('open'));
document.querySelector('#rail-close').addEventListener('click', () => rail.classList.remove('open'));
rail.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => rail.classList.remove('open')));
